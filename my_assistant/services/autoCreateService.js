const Task = require("../models/Task");
const Reminder = require("../models/Reminder");
const Note = require("../models/Note");
const { formatISTDate } = require("../utils/dateFormatter");
/**
 * Auto-create reminder and note for a task
 * @param {Object} task - The created task object
 * @returns {Promise<Object>} - Returns the task with reminderId and noteId
 */
async function autoCreateDependencies(task, hasExplicitTime = false) {
  try {
    console.log(`🔄 Auto-creating dependencies for task: "${task.title}"`);

    let reminderId = null;
    let noteId = null;
    let savedReminder = null;
    let savedNote = null;

    // 1. Auto-create reminder (if task has due date)
    if (task.dueDate) {
      const reminderDate = new Date(task.dueDate);

      if (hasExplicitTime) {
        // User gave a specific time, keep that time
        console.log(`  ⏰ Using user-specified time: ${reminderDate}`);
      } else {
        reminderDate.setHours(9, 0, 0, 0);
      }
      console.log(`  ⏰ Reminder will be set for: ${reminderDate}`);
      const reminderTitle = `${task.title}`;
      const reminder = new Reminder({
        title: reminderTitle,
        remindAt: reminderDate,
        taskId: task._id,
        isAutoGenerated: true,
      });

      savedReminder = await reminder.save();
      reminderId = savedReminder._id;
      console.log(
        `  ✅ Reminder created: "${reminderTitle}" with ID: ${reminderId}`,
      );
    } else {
      console.log(`  ⚠️ No due date, skipping reminder creation`);
    }

    // 2. Auto-create note
    const noteTitle = `${task.title}`;
    const noteContent = `Task: ${task.title}\nPriority: ${task.priority}\nCreated: ${formatISTDate(new Date())}\n\n---\nAdd your notes here...`;
    const note = new Note({
      title: noteTitle,
      content: noteContent,
      taskId: task._id,
      isAutoGenerated: true,
    });

    savedNote = await note.save();
    noteId = savedNote._id;
    console.log(`  ✅ Note created: "${noteTitle}" with ID: ${noteId}`);

    // 3. CRITICAL: Update task with foreign keys (reminderId and noteId)
    if (reminderId) {
      task.reminderId = reminderId;
    }
    if (noteId) {
      task.noteId = noteId;
    }

    // THIS IS THE KEY LINE - MUST BE HERE
    await task.save();
    console.log(
      `  ✅ Task updated with foreign keys - reminderId: ${reminderId}, noteId: ${noteId}`,
    );
    console.log(`✨ Auto-creation completed for task "${task.title}"`);

    return {
      task,
      reminderId,
      noteId,
      reminder: savedReminder,
      note: savedNote,
    };
  } catch (error) {
    console.error(
      `❌ Error auto-creating dependencies for task ${task._id}:`,
      error,
    );
    return { task, reminderId: null, noteId: null, error: error.message };
  }
}

/**
 * Update dependencies when task is updated
 * @param {Object} task - The updated task object
 * @param {Object} updates - What was updated
 */
async function updateDependencies(task, updates, previousValues = {}) {
  try {
    console.log(`🔄 Updating dependencies for task: "${task.title}"`);

    // ================================
    // DUE DATE / TIME UPDATE
    // ================================
    if (updates.dueDate) {
      const oldDate = previousValues.oldDueDate
        ? new Date(previousValues.oldDueDate)
        : null;

      const newDate = new Date(task.dueDate);

      let changeType = "datetime";

      if (oldDate) {
        const oldDatePart = oldDate.toDateString();
        const newDatePart = newDate.toDateString();

        const oldTimePart = `${oldDate.getHours()}:${oldDate.getMinutes()}`;

        const newTimePart = `${newDate.getHours()}:${newDate.getMinutes()}`;

        const dateChanged = oldDatePart !== newDatePart;
        const timeChanged = oldTimePart !== newTimePart;

        if (dateChanged && !timeChanged) {
          changeType = "date";
        } else if (!dateChanged && timeChanged) {
          changeType = "time";
        } else {
          changeType = "datetime";
        }
      }

      // =====================================
      // UPDATE EXISTING REMINDER
      // =====================================
      if (task.reminderId) {
        const reminder = await Reminder.findById(task.reminderId);

        if (reminder) {
          reminder.remindAt = task.dueDate;
          reminder.title = task.title;

          await reminder.save();

          console.log(`  ✅ Reminder ${changeType} updated successfully`);
        }
      }

      // =====================================
      // CREATE REMINDER IF NOT EXISTS
      // =====================================
      else {
        const reminder = new Reminder({
          title: task.title,
          remindAt: task.dueDate,
          taskId: task._id,
          isAutoGenerated: true,
        });

        const savedReminder = await reminder.save();

        task.reminderId = savedReminder._id;
        await task.save();

        console.log(`  ✅ New reminder created`);
      }

      // Save change type for reply
      updates.changeType = changeType;
    }

    // ================================
    // TITLE UPDATE
    // ================================
    if (updates.title) {
      // Update Reminder Title
      if (task.reminderId) {
        const reminder = await Reminder.findById(task.reminderId);

        if (reminder) {
          reminder.title = task.title;
          await reminder.save();

          console.log(`  ✅ Reminder title updated`);
        }
      }

      // Update Note Title
      if (task.noteId) {
        const note = await Note.findById(task.noteId);

        if (note) {
          note.title = task.title;
          await note.save();

          console.log(`  ✅ Note title updated`);
        }
      }
    }

    console.log(`✨ Dependency update completed`);
  } catch (error) {
    console.error(`❌ Error updating dependencies:`, error);
  }
}
